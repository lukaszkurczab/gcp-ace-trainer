#!/usr/bin/env node
// T2.5 stage 3: generates the native first screen's design inputs from the React Native sources, so the
// two stacks cannot drift by hand:
//   - native/first-screen/ios/FirstScreenTokens.swift   ← src/theme/tokens.ts (colors light/dark, spacing, radius, type)
//   - native/first-screen/ios/FirstScreenStrings.swift  ← src/locales/<locale>/common.json (the few native-only strings)
//   - native/first-screen/ios/FirstScreenAssets.xcassets ← src/assets/icons/*.svg (template) + brand marks
// Run: node --import tsx scripts/generateFirstScreenNative.mjs [--check]
// `--check` exits 1 when a generated file is missing or differs (used by the test suite).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "native/first-screen/ios");
const LOCALES = ["en", "de", "es", "et", "fr", "it", "pl"];
/** Native-only strings: key in `common.json` → Swift name. Everything else comes rendered in the record. */
const STRINGS = { "Loading…": "loading", "Opening…": "opening" };
const HEADER = "// GENERATED by scripts/generateFirstScreenNative.mjs from the React Native sources. Do not edit.\n";

function camel(parts) {
  return parts.map((part, index) => index === 0 ? part : part[0].toUpperCase() + part.slice(1)).join("");
}

function parseColor(value) {
  const hex = /^#([0-9a-f]{6})$/iu.exec(value);
  if (hex) {
    const n = Number.parseInt(hex[1], 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
  }
  const rgba = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/u.exec(value);
  if (rgba) return [Number(rgba[1]), Number(rgba[2]), Number(rgba[3]), Number(rgba[4])];
  throw new Error(`unsupported color ${value}`);
}

function flatten(object, prefix = []) {
  return Object.entries(object).flatMap(([key, value]) => typeof value === "string" ? [[camel([...prefix, key]), value]] : flatten(value, [...prefix, key]));
}

function swiftNumber(value) {
  return Number.isInteger(value) ? `${value}` : `${Number(value.toFixed(4))}`;
}

function rgba(value) {
  const [r, g, b, a] = parseColor(value);
  return `FirstScreenRGBA(r: ${r}, g: ${g}, b: ${b}, a: ${swiftNumber(a)})`;
}

const WEIGHTS = { "400": "regular", "500": "medium", "600": "semibold", "700": "bold" };

export function renderTokens(tokens) {
  const light = flatten(tokens.colors.light);
  const dark = new Map(flatten(tokens.colors.dark));
  const names = light.map(([name]) => name);
  if (names.length !== dark.size || names.some((name) => !dark.has(name))) throw new Error("light and dark palettes differ in shape");
  const lines = [HEADER, "// Source: src/theme/tokens.ts", "import Foundation", "", "public struct FirstScreenRGBA: Equatable {",
    "  public let r: Double, g: Double, b: Double, a: Double", "}", "", "public struct FirstScreenPalette: Equatable {"];
  for (const name of names) lines.push(`  public let ${name}: FirstScreenRGBA`);
  lines.push("}", "", "public struct FirstScreenTextStyle: Equatable {", "  public let size: Double", "  public let lineHeight: Double", "  public let weight: String", "}", "",
    "public enum FirstScreenTokens {");
  for (const mode of ["light", "dark"]) {
    const values = new Map(flatten(tokens.colors[mode]));
    lines.push(`  public static let ${mode} = FirstScreenPalette(`);
    lines.push(names.map((name) => `    ${name}: ${rgba(values.get(name))}`).join(",\n"));
    lines.push("  )");
  }
  lines.push("  public enum Spacing {");
  for (const [name, value] of Object.entries(tokens.spacing)) lines.push(`    public static let ${name}: Double = ${swiftNumber(value)}`);
  lines.push("  }", "  public enum Radius {");
  for (const [name, value] of Object.entries(tokens.radius)) lines.push(`    public static let ${name}: Double = ${swiftNumber(value)}`);
  lines.push("  }", "  public enum Typography {");
  for (const [name, style] of Object.entries(tokens.typography)) {
    const weight = WEIGHTS[style.fontWeight];
    if (!weight) throw new Error(`unsupported weight ${style.fontWeight}`);
    lines.push(`    public static let ${name} = FirstScreenTextStyle(size: ${swiftNumber(style.fontSize)}, lineHeight: ${swiftNumber(style.lineHeight)}, weight: "${weight}")`);
  }
  lines.push("  }", "}", "");
  return lines.join("\n");
}

function swiftString(value) {
  return JSON.stringify(value).replace(/\\u([0-9a-f]{4})/giu, (_match, hex) => `\\u{${hex}}`);
}

export function renderStrings(readCommon) {
  const lines = [HEADER, "// Source: src/locales/<locale>/common.json", "import Foundation", "", "public struct FirstScreenNativeStrings: Equatable {"];
  for (const name of Object.values(STRINGS)) lines.push(`  public let ${name}: String`);
  lines.push("", "  public static let supportedLocales: [String] = [" + LOCALES.map((locale) => `"${locale}"`).join(", ") + "]", "",
    "  /// Exact app locale first, then its language, then English.", "  public static func forLocale(_ locale: String?) -> FirstScreenNativeStrings {",
    "    let language = locale.map { String($0.split(separator: \"-\").first ?? Substring($0)).lowercased() }", "    switch language {");
  for (const locale of LOCALES) {
    const common = readCommon(locale);
    const args = Object.entries(STRINGS).map(([key, name]) => {
      const value = common[key];
      if (typeof value !== "string" || value.length === 0) throw new Error(`missing ${locale} common:${key}`);
      return `${name}: ${swiftString(value)}`;
    });
    if (locale === "en") continue;
    lines.push(`    case "${locale}": return FirstScreenNativeStrings(${args.join(", ")})`);
  }
  const en = readCommon("en");
  lines.push(`    default: return FirstScreenNativeStrings(${Object.entries(STRINGS).map(([key, name]) => `${name}: ${swiftString(en[key])}`).join(", ")})`);
  lines.push("    }", "  }", "}", "");
  return lines.join("\n");
}

const CONTENTS_ROOT = JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n";
function imageset(file, template) {
  return JSON.stringify({
    images: [{ filename: file, idiom: "universal" }],
    info: { author: "xcode", version: 1 },
    properties: { "preserves-vector-representation": true, ...(template ? { "template-rendering-intent": "template" } : {}) },
  }, null, 2) + "\n";
}

/** All generated files as { relative path → content }. */
export async function renderAll() {
  const tokens = await import(pathToFileURL(path.join(ROOT, "src/theme/tokens.ts")).href);
  const files = new Map();
  files.set("FirstScreenTokens.swift", renderTokens(tokens));
  files.set("FirstScreenStrings.swift", renderStrings((locale) => JSON.parse(readFileSync(path.join(ROOT, "src/locales", locale, "common.json"), "utf8"))));
  const assets = "FirstScreenAssets.xcassets";
  files.set(`${assets}/Contents.json`, CONTENTS_ROOT);
  const iconDir = path.join(ROOT, "src/assets/icons");
  for (const file of readdirSync(iconDir).filter((name) => name.endsWith(".svg")).sort()) {
    const svg = readFileSync(path.join(iconDir, file), "utf8");
    if (!svg.includes("currentColor")) continue; // multi-colour provider logos are not drawn natively
    const name = `icon-${file.slice(0, -4)}`;
    // Template images are tinted by SwiftUI; CoreSVG has no `currentColor`, so draw in black.
    files.set(`${assets}/${name}.imageset/${file}`, svg.replaceAll("currentColor", "#000000"));
    files.set(`${assets}/${name}.imageset/Contents.json`, imageset(file, true));
  }
  for (const treatment of ["mint", "navy"]) {
    const file = `patternly-mark-${treatment}.svg`;
    files.set(`${assets}/brand-mark-${treatment}.imageset/${file}`, readFileSync(path.join(ROOT, "src/assets/brand/mark", file), "utf8"));
    files.set(`${assets}/brand-mark-${treatment}.imageset/Contents.json`, imageset(file, false));
  }
  return files;
}

function listExisting(dir, prefix = "") {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory()
    ? listExisting(path.join(dir, entry.name), `${prefix}${entry.name}/`)
    : [`${prefix}${entry.name}`]);
}

/** Returns the relative paths that are missing, stale or no longer generated. */
export async function checkGenerated() {
  const files = await renderAll();
  const problems = [];
  for (const [relative, content] of files) {
    const target = path.join(OUT, relative);
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) problems.push(relative);
  }
  for (const relative of listExisting(path.join(OUT, "FirstScreenAssets.xcassets"), "FirstScreenAssets.xcassets/")) {
    if (!files.has(relative)) problems.push(relative);
  }
  return problems;
}

async function main() {
  if (process.argv.includes("--check")) {
    const problems = await checkGenerated();
    if (problems.length) {
      console.error(`FIRST_SCREEN_NATIVE_GENERATED=stale\n${problems.join("\n")}\nRun: node --import tsx scripts/generateFirstScreenNative.mjs`);
      process.exit(1);
    }
    console.log("FIRST_SCREEN_NATIVE_GENERATED=current");
    return;
  }
  const files = await renderAll();
  rmSync(path.join(OUT, "FirstScreenAssets.xcassets"), { recursive: true, force: true });
  for (const [relative, content] of files) {
    const target = path.join(OUT, relative);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`FIRST_SCREEN_NATIVE_GENERATED=${files.size} files`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
