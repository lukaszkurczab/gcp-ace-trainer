import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { checkNotes, repositories, runAtlas } from './atlas.mjs';
import { applyRetirement, prepareRetirement } from './retireOrphanNotes.mjs';

async function fixture(t) {
  const workspace = realpathSync(mkdtempSync(join(tmpdir(), 'patternly-atlas-retirement-')));
  t.after(() => rmSync(workspace, { recursive: true, force: true }));
  const vault = join(workspace, 'vault');
  const put = (relative, text) => { const target = join(workspace, relative); mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, text); };
  for (const repo of repositories) {
    mkdirSync(join(workspace, repo));
    execFileSync('git', ['init', '-q', join(workspace, repo)]);
    put(`${repo}/src/current.ts`, 'export const current = 1;\n');
    put(`${repo}/.gitignore`, '.agent/\n');
    execFileSync('git', ['-C', join(workspace, repo), 'add', '.']);
  }
  put('patternly/src/obsolete.ts', 'export const obsolete = true;\n');
  put('patternly/scripts/docAtlas/catalog.json', JSON.stringify({ date: '2026-10-19', areas: [], files: {}, flows: [] }));
  execFileSync('git', ['-C', join(workspace, 'patternly'), 'add', '.']);
  for (const repo of repositories) execFileSync('git', ['-C', join(workspace, repo), '-c', 'user.name=Atlas Fixture', '-c', 'user.email=atlas@example.invalid', '-c', 'commit.gpgsign=false', 'commit', '-qm', 'fixture']);
  put('vault/Atlas/Atlas aplikacji.md', '# Atlas aplikacji\n');
  put('vault/Atlas/Przepływy.md', '# Przepływy\n');
  t.mock.method(console, 'log', () => {});
  await runAtlas('build', { workspace, vault });
  rmSync(join(workspace, 'patternly/src/obsolete.ts'));
  const plan = prepareRetirement({ workspace, vault });
  assert.equal(plan.rows.length, 1);
  return { workspace, vault, plan, put, index: join(workspace, 'patternly/scripts/docAtlas/atlas-index.json'), journal: join(workspace, 'patternly/.agent/private/docAtlas-retirement/journal.json') };
}

test('reviewed exact generated orphan retirement preserves manual notes and canonical source-review baseline', async t => {
  const f = await fixture(t);
  f.put('vault/Atlas/Manual.md', '# Manual requirement\n');
  const before = JSON.parse(readFileSync(f.index, 'utf8'));
  assert.equal(applyRetirement(f.plan, f).retiredNotes, 1);
  assert.equal(existsSync(join(f.vault, f.plan.rows[0].path)), false);
  assert.equal(readFileSync(join(f.vault, 'Atlas/Manual.md'), 'utf8'), '# Manual requirement\n');
  const pruned = JSON.parse(readFileSync(f.index, 'utf8'));
  assert.deepEqual(pruned.repositories, before.repositories, 'retirement cannot refresh source hashes or claim review');
  assert.equal(Object.keys(pruned.notes).length, Object.keys(before.notes).length - 1);
  await runAtlas('build', f);
  assert.deepEqual(checkNotes(f.vault, JSON.parse(readFileSync(f.index, 'utf8'))), []);
});

test('changed generated bytes, unplanned rows and source drift fail before index or note mutation', async t => {
  const f = await fixture(t);
  const originalIndex = readFileSync(f.index, 'utf8');
  const note = join(f.vault, f.plan.rows[0].path);
  const text = readFileSync(note, 'utf8');
  writeFileSync(note, `${text}\nManual addition\n`);
  assert.throws(() => applyRetirement(f.plan, f), /edited-or-rebound-note/);
  assert.equal(readFileSync(f.index, 'utf8'), originalIndex);
  writeFileSync(note, text);
  assert.throws(() => applyRetirement({ ...f.plan, rows: [...f.plan.rows, { path: 'Atlas/Manual.md', sha256: '0'.repeat(64) }] }, f), /stale-plan/);
  f.put('patternly/src/current.ts', 'export const current = 2;\n');
  assert.throws(() => applyRetirement(f.plan, f), /stale-plan/);
  assert.equal(readFileSync(f.index, 'utf8'), originalIndex);
  assert.equal(readFileSync(note, 'utf8'), text);
});

test('a symlinked orphan cannot remove or read an external target', async t => {
  const f = await fixture(t);
  const note = join(f.vault, f.plan.rows[0].path);
  f.put('outside.md', 'private sentinel');
  rmSync(note);
  symlinkSync(join(f.workspace, 'outside.md'), note);
  assert.throws(() => applyRetirement(f.plan, f), /symlink/);
  assert.equal(readFileSync(join(f.workspace, 'outside.md'), 'utf8'), 'private sentinel');
  assert.equal(existsSync(f.journal), false);
});

test('interruption leaves an exact resumable journal and normal rendering refuses to bypass it', async t => {
  const f = await fixture(t);
  assert.throws(() => applyRetirement(f.plan, { ...f, onRowRetired() { throw new Error('simulated interruption'); } }), /simulated interruption/);
  assert.equal(existsSync(f.journal), true);
  assert.equal(existsSync(join(f.vault, f.plan.rows[0].path)), false);
  await assert.rejects(() => runAtlas('build', f), /retirement-pending/);
  assert.equal(applyRetirement(f.plan, f).retiredNotes, 1);
  assert.equal(existsSync(f.journal), false);
  await runAtlas('build', f);
  assert.deepEqual(checkNotes(f.vault, JSON.parse(readFileSync(f.index, 'utf8'))), []);
});

test('live owner and concurrent index changes preserve the pending operation', async t => {
  const f = await fixture(t);
  assert.throws(() => applyRetirement(f.plan, { ...f, onRowRetired() { throw new Error('interrupt'); } }), /interrupt/);
  const journal = JSON.parse(readFileSync(f.journal, 'utf8'));
  writeFileSync(f.journal, JSON.stringify({ ...journal, ownerPid: process.pid }));
  assert.throws(() => applyRetirement(f.plan, f), /live-owner/);
  writeFileSync(f.journal, JSON.stringify(journal));
  const pruned = readFileSync(f.index, 'utf8');
  writeFileSync(f.index, `${pruned} `);
  assert.throws(() => applyRetirement(f.plan, f), /concurrent-index-change/);
  assert.equal(readFileSync(f.index, 'utf8'), `${pruned} `);
  assert.equal(existsSync(f.journal), true);
});

test('a killed writer resumes from its persisted exact-row journal in a new process', async t => {
  const f = await fixture(t);
  const planFile = join(f.workspace, 'reviewed-plan.json');
  writeFileSync(planFile, JSON.stringify(f.plan));
  const driver = `import {readFileSync} from 'node:fs'; import {applyRetirement} from ${JSON.stringify(new URL('./retireOrphanNotes.mjs', import.meta.url).href)}; const plan=JSON.parse(readFileSync(process.argv[1],'utf8')); applyRetirement(plan,{workspace:plan.workspace,vault:plan.vault,onRowRetired(){process.kill(process.pid,'SIGKILL');}});`;
  const killed = spawnSync(process.execPath, ['--input-type=module', '-e', driver, planFile], { encoding: 'utf8' });
  assert.equal(killed.signal, 'SIGKILL');
  assert.ok(JSON.parse(readFileSync(f.journal, 'utf8')).ownerPid > 0);
  assert.equal(existsSync(join(f.vault, f.plan.rows[0].path)), false);
  assert.equal(applyRetirement(f.plan, f).retiredNotes, 1);
  assert.equal(existsSync(f.journal), false);
  await runAtlas('build', f);
  assert.deepEqual(checkNotes(f.vault, JSON.parse(readFileSync(f.index, 'utf8'))), []);
});
