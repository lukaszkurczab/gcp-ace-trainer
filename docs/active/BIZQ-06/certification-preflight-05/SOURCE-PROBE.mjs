import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const require = createRequire(resolve(appRoot, "package.json"));
require("tsx/cjs");
const { contentPackageRuntimeOwner } = require(resolve(appRoot, "src/application/contentPackageRuntimeOwner.ts"));
const { detailLines } = require(resolve(appRoot, "src/features/practice/feedbackDetails.ts"));
const { projectCanonicalSourceLinks } = require(resolve(appRoot, "src/application/canonical/canonicalSourceLinks.ts"));
const trackId = "aws-certified-solutions-architect-associate";
const questionId = "aws-saa-c03-architecture-001-odk096";
const sourcePath = resolve(appRoot, "../patternly-content/content", trackId, "aws_secure_architecture_foundations/architecture_review.json");
const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const bytesHash = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");
const { track, runtime } = await contentPackageRuntimeOwner.resolveForDiscovery(trackId, "certification");
const question = track.getQuestion(questionId);
assert.deepEqual(question, read(sourcePath).find((item) => item.questionId === questionId));
assert.equal(runtime.familyId, "certification");
const mode = track.modes.find((item) => item.modeId === "certification-focus-practice");
assert.equal(mode.availability, "immediate");
assert.equal(mode.selection.kind, "node");
assert.equal(mode.selection.nodeId, question.nodeId);
assert.ok(track.getPool(mode.modeId).some((item) => item.questionId === questionId));
const lockPath = resolve(appRoot, "src/content/generated/canonical-content/content-lock.json");
const releasePath = resolve(appRoot, "integration/contracts/content-release/release.lock.json");
const admission = read(resolve(appRoot, "../patternly-content/evidence/admissions/candidate-admission-v3.json"));
const lock = read(lockPath).tracks.find((item) => item.trackId === trackId);
const release = read(releasePath).artifacts.find((item) => item.trackId === trackId);
const admitted = admission.tracks.find((item) => item.trackId === trackId);
assert.equal(lock.sha256, track.artifactSha256);
assert.equal(lock.contentVersion, track.contentVersion);
assert.equal(release.checksumSha256, track.artifactSha256);
assert.equal(release.contentVersion, track.contentVersion);
assert.equal(admitted.runtimeAdmission, "granted");
assert.equal(admitted.artifactSha256, track.artifactSha256);
assert.equal(admission.application.bundledContentLockSha256, bytesHash(lockPath));
assert.equal(admission.application.releaseLockSha256, bytesHash(releasePath));
const sourceUrls = new Set(projectCanonicalSourceLinks(question).map((item) => item.url));
const paragraphs = detailLines(question.feedback.details).filter((line) => !sourceUrls.has(line));
assert.equal(paragraphs.length, 4);
assert.deepEqual(paragraphs, Object.entries(question.feedback.details).filter(([key]) => key !== "url").map(([, value]) => value));
console.log(JSON.stringify({trackId, questionId, sourcePath, contentVersion:track.contentVersion, artifactSha256:track.artifactSha256, modeId:mode.modeId, sourceMatchesArtifact:true, currentImmediateFreePoolContainsItem:true, currentLocksAndAdmissionMatch:true, existingFormatterParagraphCount:paragraphs.length, sourceUrlsExcludedFromProse:true, marketingPublicationAuthorization:"not established by this probe"}, null, 2));
